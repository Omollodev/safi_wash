#!/usr/bin/env python3
"""
Builds static/img/icons.svg, the Lucide icon sprite used by {% icon "name" %}.

Why a sprite: one small cached file, no CDN, no JavaScript, and icons inherit the text colour.
Lucide is ISC licensed (https://lucide.dev). To add an icon: put its name in ICONS below, then run

    npm install --prefix /tmp/lucide lucide-static
    python scripts/build_icon_sprite.py /tmp/lucide/node_modules/lucide-static/icons

`python manage.py test apps.core` fails if a template uses an icon that is missing from the sprite.
"""
import re
import sys
from pathlib import Path

ICONS = """
arrow-left arrow-right arrow-up-right trending-up trending-down minus
bell calendar-check calendar-plus car-front chart-no-axes-combined check check-check chevron-down
circle circle-alert circle-check circle-plus circle-user clipboard-check clipboard-plus clock compass contact
droplet droplets eye eye-off gauge history info key-round list-checks log-in log-out mail mail-check map-pin
message-circle pencil-square-placeholder phone play plus printer radio receipt refresh-cw rotate-ccw search shield
shield-check smartphone sparkles square-pen star tag tags terminal timer trash-2 triangle-alert user user-check
user-plus users wallet wind x zap activity banknote layout-dashboard external-link inbox circle-dot settings
""".split()
ICONS = [i for i in ICONS if not i.endswith("-placeholder")]


def main(src: Path, out: Path):
    symbols, missing = [], []
    for name in sorted(set(ICONS)):
        f = src / f"{name}.svg"
        if not f.exists():
            missing.append(name)
            continue
        body = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
        body = re.sub(r"\s+", " ", body).strip()
        symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{body}</symbol>')
    if missing:
        sys.exit(f"Not in lucide-static: {', '.join(missing)}")
    out.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
        "<!-- Lucide icons, ISC licence, https://lucide.dev. Generated by scripts/build_icon_sprite.py -->\n"
        + "\n".join(symbols) + "\n</svg>\n"
    )
    print(f"{len(symbols)} icons -> {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(__file__).resolve().parent.parent / "static" / "img" / "icons.svg")
